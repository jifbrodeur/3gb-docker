-- Paquetage de tests unitaires utPLSQL de cours_tapi, repris de
-- « Lecon - 13 - Generation API/cours/test » (test_cours_tapi.pks/.pkb),
-- puis execution des tests.
--
-- Corrections par rapport a la lecon 13 (4 tests echouaient) :
--   ins_cours_null, upd_cours_inexistant, del_cours_inexistant :
--     l_status_code est un NUMBER ; utPLSQL refuse de le comparer a un
--     texte ('-1400'), on compare donc a un nombre.
--   upd_cours_inexistant : cours_tapi renvoie SQLCODE de NO_DATA_FOUND,
--     soit 100 (et non -1403, qui est le numero du message ORA-01403).
--   get_cours : get_cours(1, 2, 2, 2) sautait 2 rangees d'un resultat qui
--     n'en contient qu'une ; on garde la pagination par defaut.
--
-- Prerequis : utPLSQL v3 installe dans le schema UT3 (synonymes publics)
-- et 30_cours.sql, 31_cours_tapi.spc et 31_cours_tapi.bdy deja joues.
--
-- Execute connecte AVEC LE COMPTE APPLICATIF :
--   docker compose exec oracle-db sqlplus "app3gb/<APP_USER_PASSWORD>@//localhost:1521/FREEPDB1" "@/sql/40_test_cours_tapi.sql"
--
-- Pour relancer seulement les tests, sans recompiler :
--   BEGIN ut.run('test_cours_tapi'); END;
-- =====================================================================

